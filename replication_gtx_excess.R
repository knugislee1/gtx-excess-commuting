## ---- 8. Uniqueness of every transportation-problem solution, and Paju's own lower bound -------------------------
## For every problem used in the paper (146: step 1 distance and 2023 time, step 1 actual time for 36 months, step 2
## three costs for 36 months) we check (1) that the optimal basis is non-degenerate (positive cells = m + n - 1),
## (2) that every observed pair outside the basis has a strictly positive reduced cost, which makes the optimal
## assignment unique, and (3) record the minimum commute assigned to Paju in the regional optimum next to Paju's own
## lower bound (Paju's workers fill the nearest jobs first, each destination's capacity being its total D_j, with no competition).
section(8, "Uniqueness of all 146 LP solutions; Paju-only lower bound", "si_benchmark.csv", {
  dt <- get_od1(); cost <- build_cost(dt)
  months <- sort(unique(dt[ym <= "2025-12", ym]))
  check_lp <- function(X, cvec, label) {
    zo <- sort(unique(X$o)); zd <- sort(unique(X$d)); io <- match(X$o, zo); id <- match(X$d, zd)
    N <- matrix(0, length(zo), length(zd)); N[cbind(io, id)] <- X$cnt; a <- rowSums(N); b <- colSums(N)
    C <- matrix(5 * max(cvec), length(zo), length(zd)); C[cbind(io, id)] <- cvec
    pl <- data.table(transport::transport(a, b, costm = C, method = "networkflow"))
    m <- length(zo); n <- length(zd); nb <- nrow(pl)
    ## dual variables u, v from the basic cells (a spanning tree): u_i + v_j = c_ij on the basis
    adj <- vector("list", m + n); for (k in seq_len(nb)) { i <- pl$from[k]; j <- m + pl$to[k]; adj[[i]] <- c(adj[[i]], k); adj[[j]] <- c(adj[[j]], k) }
    u <- rep(NA_real_, m); v <- rep(NA_real_, n); u[1] <- 0; q <- 1L; seen <- rep(FALSE, m + n); seen[1] <- TRUE
    while (length(q)) {
      node <- q[1]; q <- q[-1]
      for (k in adj[[node]]) {
        i <- pl$from[k]; j <- pl$to[k]; cij <- C[i, j]
        if (node <= m) { if (!seen[m + j]) { v[j] <- cij - u[i]; seen[m + j] <- TRUE; q <- c(q, m + j) } }
        else           { if (!seen[i])     { u[i] <- cij - v[j]; seen[i] <- TRUE;     q <- c(q, i) } }
      }
    }
    connected <- all(seen)
    basic <- paste(io, id) %in% paste(pl$from, pl$to)
    r <- cvec - u[io] - v[id]; rn <- r[!basic]; tol <- 1e-9 * max(cvec)       # reduced costs of observed pairs outside the basis
    ip <- match(PAJU, zo); OP <- a[ip]
    alloc <- pl[from == ip, sum(mass * C[cbind(from, to)])] / OP                # Paju's assigned minimum commute
    row <- data.table(d = id[io == ip], c = cvec[io == ip]); row <- merge(row, data.table(d = seq_along(zd), D = b), by = "d")[order(c)]
    row[, before := shift(cumsum(D), fill = 0)][, take := pmin(D, pmax(0, OP - before))]; own <- row[, sum(take * c) / sum(take)]   # Paju-only lower bound
    data.table(lp = label, zones_o = m, zones_d = n, basic_cells = nb, m_plus_n_minus_1 = m + n - 1, nondegenerate = (nb == m + n - 1), tree_connected = connected,
               min_basic_mass = min(pl$mass), nonbasic_observed_cells = sum(!basic),
               min_reduced_cost = if (connected) min(rn, na.rm = TRUE) else NA_real_,
               zero_reduced_cells = if (connected) sum(rn <= tol) else NA_integer_,
               zero_reduced_paju_row = if (connected) sum(rn <= tol & io[!basic] == ip) else NA_integer_,
               paju_allocated = alloc, paju_own_bound = own, paju_O = OP, paju_D = b[match(PAJU, zd)])
  }
  res <- list(); t0 <- Sys.time()
  B <- dt[ym >= "2024-01" & ym <= "2024-12", .(cnt = sum(cnt) / 12), by = .(o, d)]; B <- merge(B, cost[, .(o, d, cd23, ct23, ct_all)], by = c("o", "d"))
  res[[length(res) + 1]] <- check_lp(B, B$cd23, "step1 | distance 2023 | fixed")
  res[[length(res) + 1]] <- check_lp(B, B$ct23, "step1 | time 2023 | fixed")
  for (m in months) {
    cur <- dt[ym == m, .(o, d, ct_cur = tw / cnt)]; X <- merge(B[, .(o, d, cnt, ct_all)], cur, by = c("o", "d"), all.x = TRUE); X[is.na(ct_cur), ct_cur := ct_all]
    res[[length(res) + 1]] <- check_lp(X, X$ct_cur, paste("step1 | actual time |", m))
  }
  cat("    step 1 done:", length(res), "problems,", round(as.numeric(difftime(Sys.time(), t0, units = "secs"))), "s\n")
  for (m in months) {
    X <- merge(dt[ym == m], cost[, .(o, d, cd23, ct23)], by = c("o", "d")); X[, ct_cur := tw / cnt]
    res[[length(res) + 1]] <- check_lp(X, X$cd23,   paste("step2 | distance 2023 |", m))
    res[[length(res) + 1]] <- check_lp(X, X$ct23,   paste("step2 | time 2023 |", m))
    res[[length(res) + 1]] <- check_lp(X, X$ct_cur, paste("step2 | actual time |", m))
  }
  out <- rbindlist(res); fwrite(out, P("si_benchmark.csv"))
  cat("    all problems:", nrow(out), "|", round(as.numeric(difftime(Sys.time(), t0, units = "secs"))), "s\n")
  cat("    non-degenerate:", sum(out$nondegenerate), "| tree connected:", sum(out$tree_connected), "| zero reduced-cost cells (max over problems):", max(out$zero_reduced_cells), "| Paju row:", max(out$zero_reduced_paju_row), "\n")
  cat("    min reduced cost: distance", out[grepl("distance", lp), min(min_reduced_cost)], "m | time", out[grepl("time", lp), min(min_reduced_cost)], "min\n")
  cat("    min basic mass:", min(out$min_basic_mass), "\n")
  out[, gap := paju_allocated - paju_own_bound]
  print(out[, .(n = .N, alloc_min = min(paju_allocated), alloc_max = max(paju_allocated), own_min = min(paju_own_bound), own_max = max(paju_own_bound), gap_min = min(gap), gap_max = max(gap)),
            by = .(kind = sub(" \\| [^|]*$", "", lp))])
})

