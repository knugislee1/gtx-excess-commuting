  cat(sprintf("    pairs absent in 2023: %d of %d observed in 2024-25 | share of commuters %.3f%% (2024), %.3f%% (2025) | Paju %.3f%%\n",
      sh[absent == TRUE, uniqueN(paste(o, d))], sh[, uniqueN(paste(o, d))],
      sh[ym <= "2024-12", 100 * sum(cnt[absent %in% TRUE]) / sum(cnt)], sh[ym >= "2025-01", 100 * sum(cnt[absent %in% TRUE]) / sum(cnt)],
      sh[o == PAJU, 100 * sum(cnt[absent %in% TRUE]) / sum(cnt)]))
  dt <- dt0[ym <= "2025-12"]; months <- sort(unique(dt$ym))
  solve_one <- function(a, b, C) lp_min(a, b, C)
  build <- function(dtx, cost) {
    ## step 2 (monthly margins)
    s2 <- rbindlist(lapply(months, function(m) {
      X <- merge(dtx[ym == m], cost[, .(o, d, cd23, ct23)], by = c("o", "d")); X[, ct_cur := tw / cnt]
      zo <- sort(unique(X$o)); zd <- sort(unique(X$d)); io <- match(X$o, zo); id <- match(X$d, zd)
      N <- matrix(0, length(zo), length(zd)); N[cbind(io, id)] <- X$cnt; a <- rowSums(N); b <- colSums(N)
      mk <- function(v) { C <- matrix(5 * max(v), length(zo), length(zd)); C[cbind(io, id)] <- v; C }
