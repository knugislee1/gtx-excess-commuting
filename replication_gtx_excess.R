#!/usr/bin/env Rscript
## =============================================================================
## replication_gtx_excess.R
##
## Replication code for
##   "Does opening a regional express rail line increase excess commuting?
##    Evidence from Seoul, Korea"   (Transport Findings, revision)
##
## One file, numbered sections. Section k reads the files written by the
## sections before it, and is skipped when its output files already exist
## (FORCE=true recomputes everything). Sections can be run one by one with
## ONLY=3,4 (see "Usage").
##
##   0  Settings, embedded lookup tables, helper functions
##   1  Raw daily files (OA-22300) -> daily commuting aggregates (od1_YYYYMMDD.csv.gz)
##   2  Independent re-aggregation of three days from the raw files, compared with
##      the aggregates already on disk
##   3  Monthly origin-destination panel (3-day sums, zone harmonization)
##   4  Step 2 panel: minimum commute from a transportation problem solved for each
##      month's own margins (panel_xc_monthly.csv)
##   5  Step 1 panel: minimum commute with margins fixed at their 2024 means (panel_xc.csv)
##   6  Estimates: pre-opening-level index, 44-district comparison screen, median-
##      subtracted difference of differences, rank-based p, moving-block bootstrap,
##      comparison-group variants, Figure 1; both steps
##   7  Pre-opening trend, placebo opening date, last-six-months baseline
##   8  Uniqueness of every transportation-problem solution; Paju-only lower bound
##   9  Sensitivity to the cost rule for pairs absent in 2023
##  10  Estimates with the Paju-only lower bound as the benchmark
##  11  Two-step comparison; margins fixed at 2025 means; fixed-margin robustness table
##  12  Destinations of Paju's commuters; Gangnam-bound trips; distance bands; Figure S2
##  13  Data record (cells, zones, pairs absent in 2023)
##  14  File-by-file comparison with reference outputs (only if REF_DIR is given)
##  15  Numbers reported in the paper versus the numbers reproduced here
##
## DATA (not redistributed). Seoul Open Data Plaza, "Seoul metropolitan area de
## facto population mobility, origin-destination (OA-22300)", one zip per day
## (about 60 MB, a csv of about 360 MB inside), copyright Seoul Metropolitan
## Government, Korea Open Government License Type 1 (attribution). Section 1
## downloads the 126 sample days (about 8 GB in all; 15-30 seconds per day on the
## test machine, so roughly 30-65 minutes) with `curl`, reduces each to its
## aggregate and deletes the zip. If you already hold the daily aggregates, set
## OD1_DIR to that folder and section 1 does nothing.
##
## NOT INCLUDED. Figure 2, Figure S1 and Figure S3 are maps drawn with separate
## scripts that need boundary and OpenStreetMap files: Figure 2B and Figure S3 use
## every Tuesday to Thursday outside holidays, not only the sampled days, and
## Figure S1 uses resident registration data; available on request.
##
## SAMPLE MONTHS. The paper's estimates use January 2023 to December 2025 (108
## days). The pipeline also reads January to June 2026 (18 days; 126 in all)
## because, in the cost dictionary of sections 4-5, a pair that was not observed in
## 2023 takes the mean of all months in which it appears up to June 2026
## (COST_LAST_MONTH), and because, in the first step at actual travel times
## (section 5), a pair of the fixed 2024 assignment that is not observed in a month
## takes the same all-month mean time (ct_all). Three July 2026 days are listed as well and are read with
## LAST_MONTH=2026-07; they only add two Incheon districts created in that month,
## which are excluded from every estimate, and change no number. See the note at
## COST_LAST_MONTH and section 9, which quantifies the rule. (Checked: with
## LAST_MONTH=2026-07 every number of section 15 is unchanged. With only the 108
## days of the paper window (LAST_MONTH=2025-12; the same happens with
## COST_LAST_MONTH=2025-12), 15 of the numbers of section 15 move in the second
## decimal or in p, e.g. the p of excess time at actual travel times in step 1,
## 0.27 -> 0.29, and of excess time at 2023 travel times in step 2, 0.40 -> 0.38;
## the distance results do not move.)
##
## EMBEDDED TABLES. To avoid a dependency on boundary files, the 52 outside-Seoul
## districts' distance to Seoul City Hall and adjacency to a GTX-A district
## (GEO52_TXT) and the 426 Seoul dong's distances to four stations (SEOUL_DONG_TXT)
## are written into this file; their origin is stated at each table. The file is
## UTF-8 (Korean administrative names appear in SEOUL_DONG_TXT).
##
## REQUIREMENTS. R with the packages data.table, transport, ggplot2, patchwork,
## ggrepel, jsonlite; `curl` on the path (section 1 only). R.utils is optional (it
## makes reading the .gz aggregates faster). Tested with R 4.5.3, data.table
## 1.18.2.1, transport 0.15.4, ggplot2 4.0.2 on macOS (arm64); other versions are
## untested. Run time about 6-7 minutes without the downloads, peak memory about
## 4 GB. The random seed (20260821) is set immediately before each bootstrap.
##
## USAGE (from the folder that holds this file or any working folder)
##   Rscript replication_gtx_excess.R
##   Rscript replication_gtx_excess.R OUT=results OD1_DIR=my_daily_aggregates
##   Rscript replication_gtx_excess.R ONLY=6,7 FORCE=true
##   Rscript replication_gtx_excess.R REF_DIR=reference   # adds the section-14 comparison
##   Rscript replication_gtx_excess.R LAST_MONTH=2026-07   # also read the three July 2026 days (no number changes)
##   Rscript replication_gtx_excess.R COST_LAST_MONTH=2025-12   # cost rule for pairs absent in 2023, ending a year earlier
## =============================================================================

