## Output: Paju's estimate (own change less the comparison median's, points), its rank and p among 45 districts, for the
## two steps (xs_* = step 1, xm_* = step 2) x three measures (distance, time at 2023 times, time at actual times).
section(9, "Cost rule for pairs absent in 2023: current, pre-opening mean, dropped", "sens_absent_pairs/sens_absent_pairs.csv", {
