## Section runner: skips when all `outputs` (paths inside OUT) exist; records run time.
.times <- data.table(section = character(), title = character(), seconds = numeric(), status = character())
section <- function(id, title, outputs, code) {
  id <- as.character(id)
  if (nzchar(ONLY) && !(id %in% ONLY_IDS)) return(invisible(NULL))
  cat(sprintf("\n[%s] %s\n", id, title))
  if (!FORCE && length(outputs) > 0 && all(file.exists(P(outputs)))) {
    cat("    skipped: output files exist (FORCE=true recomputes)\n")
    .times <<- rbind(.times, data.table(section = id, title = title, seconds = 0, status = "skipped"))
    return(invisible(NULL))
  }
  t0 <- proc.time()[["elapsed"]]
  eval(substitute(code), envir = new.env(parent = globalenv()))      # each section works in its own environment
  secs <- proc.time()[["elapsed"]] - t0
  cat(sprintf("    done in %.1f s\n", secs))
  .times <<- rbind(.times, data.table(section = id, title = title, seconds = round(secs, 1), status = "run"))
  invisible(NULL)
}
with_sink <- function(file, code, append = FALSE) { sink(file, append = append); on.exit(sink(), add = TRUE); force(code) }

