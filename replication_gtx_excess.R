## ---- 0.2 Helper functions shared by several sections ----------------------------
## Cost dictionary for the transportation problems (used in sections 4, 5, 8-11).
##   cd23, ct23 : mean reported distance (m) and time (min) of the pair in 2023, weighted by commuters
##   a pair first observed after 2023 takes the mean of all its months up to COST_LAST_MONTH
##   (pairs first observed after COST_LAST_MONTH, i.e. July 2026, take their own mean)
##   absent23   : TRUE for pairs that were not observed in 2023
build_cost <- function(dt, last_month = COST_LAST_MONTH) {
  cfix     <- dt[ym <= "2023-12",    .(cd23   = sum(dw) / sum(cnt), ct23   = sum(tw) / sum(cnt)), by = .(o, d)]
  call_    <- dt[ym <= last_month,   .(cd_all = sum(dw) / sum(cnt), ct_all = sum(tw) / sum(cnt)), by = .(o, d)]
  call_new <- dt[,                   .(cd_new = sum(dw) / sum(cnt), ct_new = sum(tw) / sum(cnt)), by = .(o, d)]
  cost <- merge(call_, cfix, by = c("o", "d"), all.x = TRUE)
  cost <- merge(cost, call_new, by = c("o", "d"), all = TRUE)
  cost[is.na(cd_all), `:=`(cd_all = cd_new, ct_all = ct_new)]
  cost[, absent23 := is.na(cd23)]
  cost[is.na(cd23), cd23 := cd_all][is.na(ct23), ct23 := ct_all]
  cost[]
}
## Minimum mean commute per origin: transportation problem with origin totals a, destination totals b and
## cost matrix C (network simplex, package transport). Returns the optimal cost per commuter for each origin.
lp_min <- function(a, b, C) {
  pl <- transport::transport(a, b, costm = C, method = "networkflow")
  mn <- rep(0, length(a))
  agg <- data.table(pl)[, .(s = sum(mass * C[cbind(from, to)])), by = from]
  mn[agg$from] <- agg$s
  mn / a
}
