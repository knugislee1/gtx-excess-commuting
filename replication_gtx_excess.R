    }))
    ## step 1 (2024 margins fixed)
    B <- dtx[ym >= "2024-01" & ym <= "2024-12", .(cnt = sum(cnt) / 12), by = .(o, d)]; B <- merge(B, cost[, .(o, d, cd23, ct23, ct_all)], by = c("o", "d"))
    zo <- sort(unique(B$o)); zd <- sort(unique(B$d)); io <- match(B$o, zo); id <- match(B$d, zd)
    N <- matrix(0, length(zo), length(zd)); N[cbind(io, id)] <- B$cnt; a <- rowSums(N); b <- colSums(N)
    mk <- function(v) { C <- matrix(5 * max(v), length(zo), length(zd)); C[cbind(io, id)] <- v; C }
    fx <- data.table(o = zo, min_d = solve_one(a, b, mk(B$cd23)), min_t23 = solve_one(a, b, mk(B$ct23)))
    mt <- rbindlist(lapply(months, function(m) {
      cur <- dtx[ym == m, .(o, d, ct_cur = tw / cnt)]
      X <- merge(B[, .(o, d, ct_all)], cur, by = c("o", "d"), all.x = TRUE); X[is.na(ct_cur), ct_cur := ct_all]
      C <- matrix(5 * max(X$ct_cur), length(zo), length(zd)); C[cbind(match(X$o, zo), match(X$d, zd))] <- X$ct_cur
      data.table(ym = m, o = zo, min_t = solve_one(a, b, C))
    }))
    merge(merge(s2, fx, by = "o"), mt, by = c("o", "ym"))
  }
  estimate <- function(px) {
    px <- px[substr(o, 1, 2) != "11" & !o %chin% NEW_INCHEON]; px[, ev := ymn(ym) - ymn("2025-01")]
    px[, `:=`(xs_d = (obs_d - min_d) / 1000, xs_t = obs_t - min_t, xs_t23 = obs_t23 - min_t23,
