## ---- 14. File-by-file comparison with reference outputs (only if REF_DIR is given) --------------------------------
## REF_DIR holds the outputs of the authors' earlier scripts under the same file names (e.g. the folder data_panel/ of the
## working project). Numeric columns are compared after sorting on the key columns; a maximum absolute difference of
## 0 means identical files; differences up to 1e-6 come from the rounding of the embedded lookup tables or from the 15-digit
## text representation of numbers in csv files.
compare_tables <- function(a, b, keys) {
  a <- copy(a); b <- copy(b)
  same_cols <- identical(names(a), names(b))
  common <- intersect(names(a), names(b))
  setkeyv(a, keys); setkeyv(b, keys)
  r <- list(rows_new = nrow(a), rows_ref = nrow(b), same_columns = same_cols, max_abs_diff = NA_real_, cells_changed = NA_integer_)
  if (nrow(a) != nrow(b) || !isTRUE(all.equal(as.data.frame(a[, ..keys]), as.data.frame(b[, ..keys]), check.attributes = FALSE))) { r$status <- "ROWS DIFFER"; return(r) }
  nums <- common[sapply(a[, ..common], is.numeric)]
  chars <- setdiff(common, nums)
  dmax <- 0; nchg <- 0L
  for (v in nums) {
    x <- a[[v]]; y <- b[[v]]
    same <- (x == y) | (is.na(x) & is.na(y)); same[is.na(same)] <- FALSE        # equal values, including Inf = Inf and NA = NA
    z <- ifelse(same, 0, abs(x - y)); z[is.na(z)] <- Inf
    dmax <- max(dmax, z); nchg <- nchg + sum(z > 0)
  }
  for (v in chars) { x <- as.character(a[[v]]); y <- as.character(b[[v]]); nchg <- nchg + sum(x != y | xor(is.na(x), is.na(y)), na.rm = TRUE) }
  r$max_abs_diff <- dmax; r$cells_changed <- nchg
  char_ok <- all(vapply(chars, function(v) all(as.character(a[[v]]) == as.character(b[[v]]) | (is.na(a[[v]]) & is.na(b[[v]]))), logical(1)))
  r$status <- if (!same_cols) "COLUMNS DIFFER" else if (nchg == 0L) "identical" else if (dmax <= 1e-6 && char_ok) "same to <= 1e-6" else "DIFFERENT"
  r
}
## numbers in a text file, ignoring headings, row indices and words containing Korean characters
numeric_tokens <- function(f) {
  l <- readLines(f, warn = FALSE, encoding = "UTF-8")
  l <- l[!grepl("^\\s*$|^==|^--|^Key:", l)]
  l <- gsub("(*UTF8)(?<!\\S)(<U\\+[0-9A-Fa-f]{4}>|[\\x{AC00}-\\x{D7A3}])\\S*", " ", l, perl = TRUE)   # words that start with Korean characters (zone names), also in <U+XXXX> escape form
  l <- gsub("(*UTF8)<U\\+[0-9A-Fa-f]{4}>|[\\x{AC00}-\\x{D7A3}]", "", l, perl = TRUE)                    # Korean unit words after a number
  l <- gsub("\\b[0-9]+:", " ", l)                                                                         # row indices of printed tables
  tok <- unlist(regmatches(l, gregexpr("[-+]?[0-9]*\\.?[0-9]+([eE][-+]?[0-9]+)?", l)))
  tok[!grepl("^[0-9]{8}$", tok)]                                                                           # zone codes
}
