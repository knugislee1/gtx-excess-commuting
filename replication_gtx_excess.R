  cost0 <- build_cost(dt0)
  cpre <- dt0[ym <= "2024-12", .(cd_pre = sum(dw) / sum(cnt), ct_pre = sum(tw) / sum(cnt)), by = .(o, d)]
  cost1 <- merge(copy(cost0), cpre, by = c("o", "d"), all.x = TRUE); cost1[absent23 & !is.na(cd_pre), `:=`(cd23 = cd_pre, ct23 = ct_pre)]
  ## share of commuters on these pairs (information for the data record)
