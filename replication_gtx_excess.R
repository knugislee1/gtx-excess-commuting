## ---- 3. Monthly origin-destination panel -----------------------------------------
## Three sample days per month are summed (so cnt is a three-day sum, not a daily count). Zones are made
## consistent over time on both the origin and the destination side:
##   Hwaseong's four gu -> 41590000; Incheon Seo-gu + Geomdan-gu (split in July 2026) -> 28260000;
##   Bucheon's three gu (split in 2024) -> 41190000; Seoul dong reforms 11680740 -> 11680675 and
##   11230515, 11230533 -> 11230536.
section(3, "Monthly OD panel (3-day sums, zone harmonization)", c("od1_monthly.rds", "diag_od1_codes.csv"), {
  ff <- od1_file(SAMPLE_DAYS)
  stopifnot(all(file.exists(ff)))
  days <- as.IDate(SAMPLE_DAYS, "%Y%m%d")
  stopifnot(all(wday(days) %in% 3:5), !any(days %in% HOLIDAYS))                 # Tuesday-Thursday, no holiday
  ## design check: each month's Wednesday is the one closest to the 15th unless a holiday falls in that week
  ymd <- format(days, "%Y-%m")
  design <- rbindlist(lapply(unique(ymd), function(m) {
    cand <- as.IDate(paste0(m, "-15")) + (-3:3); wed <- cand[wday(cand) == 4]
    data.table(ym = m, follows_rule = wed %in% days[ymd == m], holiday_in_closest_week = any((wed + c(-1, 0, 1)) %in% HOLIDAYS))
  }))
  stopifnot(all(design$follows_rule | design$holiday_in_closest_week))
  cat("    sample weeks moved because of a holiday in the closest week:", paste(design[follows_rule == FALSE, ym], collapse = ", "), "\n")
  rd <- function(i) { x <- read_od1(ff[i]); x[, ym := format(days[i], "%Y-%m")]; x }
  dt <- rbindlist(lapply(seq_along(ff), rd))
  cat("    rows read:", nrow(dt), "\n")
  ## zone inventory by month: codes that appear or disappear mid-panel reveal splits and reforms
  inv  <- dt[, .(v = sum(cnt)), by = .(ym, z = o)]
  rng  <- inv[, .(first = min(ym), last = max(ym), v = sum(v)), by = z]
  susp <- rng[(first != "2023-01" | last != max(dt$ym)) & v > 1000]
  fwrite(susp[order(-v)], P("diag_od1_codes.csv"))
  cat("    zone codes appearing or disappearing mid-panel (v > 1000):", nrow(susp), "\n")
  fixz <- function(z) {
    z <- fifelse(z %chin% c("41591000", "41593000", "41595000", "41597000"), "41590000", z)
    z <- fifelse(z %chin% c("28275000", "28290000"), "28260000", z)
    z <- fifelse(substr(z, 1, 4) == "4119" & z != "41190000", "41190000", z)
    z <- fifelse(z == "11680740", "11680675", z)
    z <- fifelse(z %chin% c("11230515", "11230533"), "11230536", z)
    z
  }
  dt[, o := fixz(o)][, d := fixz(d)]
  dt <- dt[, .(cnt = sum(cnt), dw = sum(dw), tw = sum(tw)), by = .(ym, o, d)]
  inv2  <- dt[, .(v = sum(cnt)), by = .(ym, z = o)]
  rng2  <- inv2[, .(first = min(ym), last = max(ym), v = sum(v)), by = z]
  susp2 <- rng2[(first != "2023-01" | last != max(dt$ym)) & v > 1000]
  cat("    after harmonization, codes still appearing or disappearing mid-panel (v > 1000):", nrow(susp2), "\n")
  cat("    zones:", uniqueN(dt$o), "origins x", uniqueN(dt$d), "destinations | months:", uniqueN(dt$ym), "\n")
  saveRDS(dt, P("od1_monthly.rds"), compress = "gzip")   # compress = "xz" gives a 64 MB file instead of 98 MB but takes about 4.5 minutes
  cat("    saved od1_monthly.rds rows:", nrow(dt), "\n")
})

## ---- 4. Step 2 panel: margins follow each month ------------------------------------
## For every month, the transportation problem is solved with that month's own origin totals O_i
## (resident workers) and destination totals D_j (jobs taken). Three costs:
##   distance      : the pair's 2023 mean reported distance (cd23)          -> min_d
##   time, actual  : the pair's reported mean time in that month (ct_cur)   -> min_t
##   time, 2023    : the pair's 2023 mean reported time (ct23)              -> min_t23
## obs_* are the observed mean commutes in the same units; vol = commuters (three-day sum);
## p90 = 90th-percentile commute distance. Columns X_*, E_* are log-point and percent excess.
section(4, "Step 2 panel: LP for each month's own margins", "panel_xc_monthly.csv", {
  dt <- get_od1()
  cost <- build_cost(dt)
  months <- sort(unique(dt$ym))
  solve_month <- function(m) {
    X <- merge(dt[ym == m], cost[, .(o, d, cd23, ct23)], by = c("o", "d"))
    X[, ct_cur := tw / cnt]
    zo <- sort(unique(X$o)); zd <- sort(unique(X$d))
    io <- match(X$o, zo); id <- match(X$d, zd)
    N <- matrix(0, length(zo), length(zd)); N[cbind(io, id)] <- X$cnt
    a <- rowSums(N); b <- colSums(N)
    mk <- function(v, M) { C <- matrix(M, length(zo), length(zd)); C[cbind(io, id)] <- v; C }
    Cd <- mk(X$cd23, 5 * max(X$cd23)); Ct <- mk(X$ct_cur, 5 * max(X$ct_cur)); Ct2 <- mk(X$ct23, 5 * max(X$ct23))
    obs <- X[, .(obs_d = sum(cnt * cd23) / sum(cnt), obs_t = sum(cnt * ct_cur) / sum(cnt),
                 obs_t23 = sum(cnt * ct23) / sum(cnt), vol = sum(cnt),
                 p90 = ({ oo <- order(cd23); cw <- cumsum(cnt[oo]) / sum(cnt); cd23[oo][which.max(cw >= .9)] })), by = o]
    res <- data.table(ym = m, o = zo, min_d = lp_min(a, b, Cd), min_t = lp_min(a, b, Ct), min_t23 = lp_min(a, b, Ct2))
    merge(obs, res, by = "o")
  }
  cat("    solving", length(months), "months x 3 problems\n")
  pxl <- rbindlist(lapply(months, solve_month))
  pxl[, `:=`(X_d = 100 * log(obs_d / min_d), X_t = 100 * log(obs_t / min_t), X_t23 = 100 * log(obs_t23 / min_t23),
             E_d = 100 * (1 - min_d / obs_d), E_t = 100 * (1 - min_t / obs_t))]
  fwrite(pxl, P("panel_xc_monthly.csv"))
  cat("    panel_xc_monthly.csv rows:", nrow(pxl), "\n")
})

## ---- 5. Step 1 panel: margins fixed at their 2024 means ---------------------------------
## O_i and D_j are the means of the twelve months January-December 2024 (the pre-opening year). With the
## 2023 distance and the 2023 time as costs the problem is solved once, so each origin's minimum commute
## is a constant; with actual (monthly) times it is solved for every month with the same margins, so it
## moves only because reported travel times move. Observed commutes (obs_*), commuters (vol) and p90 are
## the monthly values of step 2. The step 2 minima are kept as minm_*.
section(5, "Step 1 panel: LP with 2024 margins fixed", "panel_xc.csv", {
  dt <- get_od1()
  cost <- build_cost(dt)
  B <- dt[ym >= "2024-01" & ym <= "2024-12", .(cnt = sum(cnt) / 12), by = .(o, d)]
  B <- merge(B, cost[, .(o, d, cd23, ct23, ct_all)], by = c("o", "d"))
  zo <- sort(unique(B$o)); zd <- sort(unique(B$d)); io <- match(B$o, zo); id <- match(B$d, zd)
  N <- matrix(0, length(zo), length(zd)); N[cbind(io, id)] <- B$cnt; a <- rowSums(N); b <- colSums(N)
  stopifnot(abs(sum(a) - sum(b)) < 1e-6)
  mk <- function(v, M) { C <- matrix(M, length(zo), length(zd)); C[cbind(io, id)] <- v; C }
  cat("    zones", length(zo), "x", length(zd), "| 2024 mean daily-sum commuters", round(sum(a)), "\n")
  minf_d <- lp_min(a, b, mk(B$cd23, 5 * max(B$cd23))); minf_t23 <- lp_min(a, b, mk(B$ct23, 5 * max(B$ct23)))
  months <- sort(unique(dt$ym))
  mt <- rbindlist(lapply(months, function(m) {
    cur <- dt[ym == m, .(o, d, ct_cur = tw / cnt)]
    X <- merge(B[, .(o, d, ct_all)], cur, by = c("o", "d"), all.x = TRUE); X[is.na(ct_cur), ct_cur := ct_all]   # pair not observed this month: its mean time
    C <- matrix(5 * max(X$ct_cur), length(zo), length(zd)); C[cbind(match(X$o, zo), match(X$d, zd))] <- X$ct_cur
    data.table(ym = m, o = zo, min_t = lp_min(a, b, C))
  }))
  cat("    realized-time problems:", uniqueN(mt$ym), "months\n")
  fx <- merge(mt, data.table(o = zo, min_d = minf_d, min_t23 = minf_t23), by = "o")
  pm <- fread(P("panel_xc_monthly.csv"), colClasses = list(character = "o"))
  setnames(pm, c("min_d", "min_t", "min_t23"), c("minm_d", "minm_t", "minm_t23"))
  px <- merge(pm, fx, by = c("o", "ym"), all.x = TRUE)
  cat("    rows", nrow(px), "| zones with no fixed minimum (absent from 2024 margins):", px[is.na(min_d), uniqueN(o)], "->",
      paste(px[is.na(min_d), unique(o)], collapse = ","), "\n")
  px[, `:=`(X_d = 100 * log(obs_d / min_d), X_t = 100 * log(obs_t / min_t), X_t23 = 100 * log(obs_t23 / min_t23),
            E_d = 100 * (1 - min_d / obs_d), E_t = 100 * (1 - min_t / obs_t))]
  setcolorder(px, c("o", "obs_d", "obs_t", "obs_t23", "vol", "p90", "ym", "min_d", "min_t", "min_t23", "X_d", "X_t", "X_t23", "E_d", "E_t", "minm_d", "minm_t", "minm_t23"))
  fwrite(px, P("panel_xc.csv"))
  ## the comparison screen (excess distance and excess time both positive in the pre-opening year) should pick the same districts in both steps
  q <- px[substr(o, 1, 2) != "11" & !o %chin% NEW_INCHEON]; q[, ev := ymn(ym) - ymn("2025-01")]
  scr <- function(md, mt_) q[ev %in% -12:-1, .(bd = mean(obs_d - get(md)), bt = mean(obs_t - get(mt_))), by = o][bd > 0 & bt > 0, o]
  new <- setdiff(scr("min_d", "min_t"), TRT6); old <- setdiff(scr("minm_d", "minm_t"), TRT6)
  cat("    comparison districts, step 1:", length(new), "| step 2:", length(old), "| identical:", setequal(new, old), "\n")
  pj <- q[o == PAJU]
  cat(sprintf("    Paju: minimum distance step 1 %.1f m (step 2, 2024 mean: %.1f) | minimum time at 2023 times %.2f (%.2f) | minimum time at actual times 2024 -> 2025: step 1 %.2f -> %.2f, step 2 %.2f -> %.2f\n",
    pj$min_d[1], pj[ev %in% -12:-1, mean(minm_d)], pj$min_t23[1], pj[ev %in% -12:-1, mean(minm_t23)],
    pj[ev %in% -12:-1, mean(min_t)], pj[ev %in% 0:11, mean(min_t)], pj[ev %in% -12:-1, mean(minm_t)], pj[ev %in% 0:11, mean(minm_t)]))
})

## ---- 6. Estimates (both steps) and Figure 1 ----------------------------------------------------------
## Design. Outside Seoul there are 52 districts, six with a GTX-A station (Paju, Goyang-Ilsanseo, Goyang-Deogyang,
## Hwaseong, Yongin-Giheung, Seongnam-Bundang). The comparison group is the remaining 46 less those whose excess in
## the twelve pre-opening months is not positive in distance or in time (Guri, Uiwang), i.e. 44 districts; the
## screen uses pre-opening data only. For each district the excess (observed minus minimum mean commute) is
## expressed as an index of its own mean in the twelve months before the opening (= 100). A district's estimate is
## mean(post gap) - mean(pre gap), where gap = own index - median index of the comparison districts, post = the
## twelve months after the opening (2025-01..12), pre = the twelve months before (2024-01..12). Units are points of
## the pre-opening level. p is the rank-based p: the same estimate is computed for every comparison district as if it
## were treated, against the others; p = (1 + #{placebo estimates at least as large in absolute value}) / 45.
## Intervals are moving-block bootstraps (4-month blocks, 4,000 resamples, drawn within the pre and the post window).
## `two_spec` = TRUE adds the step 2 excess (xs_d_m, xs_t_m) to the step 1 panel for Figure 1.
run_xc2 <- function(px, outdir, two_spec) {
  dir.create(outdir, recursive = TRUE, showWarnings = FALSE)
  px <- copy(px)
  px <- px[substr(o, 1, 2) != "11"]
  px <- px[!o %chin% NEW_INCHEON]          # two Incheon districts created in 2026-07: no history
  stopifnot(uniqueN(px$o) == 52, all(c("2023-01", "2025-12") %in% px$ym))
  px[, `:=`(obs_d_km = obs_d / 1000, min_d_km = min_d / 1000,
            xs_d = (obs_d - min_d) / 1000,          # excess distance (km per commuter)
            xs_t = obs_t - min_t,                   # excess time (min per commuter, each month's reported times)
            xs_t23 = obs_t23 - min_t23,             # excess time (2023 pair times)
            tot_d = (obs_d - min_d) / 1000 * vol,   # total excess distance (person-km)
            tot_t23 = (obs_t23 - min_t23) * vol)]
  if (two_spec) px[, `:=`(xs_d_m = (obs_d - minm_d) / 1000, xs_t_m = obs_t - minm_t)]   # step 2 excess, used for the step 2 column of Figure 1
  ## NB: the LP minimum is a regional optimum, so one origin's assigned mean can exceed its observed mean (negative
  ## excess). The index to the pre-opening level needs positive pre-opening excess; hence the screen below.
  cat("    districts with a non-positive excess in some month:", px[, .(neg = sum(xs_d <= 0)), by = o][neg > 0, .N], "\n")
  trt <- data.table(
    o        = c("41480000", "41287000", "41281000", "41590000", "41463000", "41135000"),
    name     = c("Paju", "GoyangIlsanW", "GoyangDeogyang", "Hwaseong", "YonginGiheung", "SeongnamBundang"),
    label    = c("Paju", "Goyang-Ilsanseo", "Goyang-Deogyang", "Hwaseong", "Yongin-Giheung", "Seongnam-Bundang"),
    corridor = c("North", "North", "North", "South", "South", "South"),
    open0    = c("2025-01", "2025-01", "2025-01", "2024-04", "2024-07", "2024-04"))   # first full month after opening
  pool_raw <- setdiff(unique(px$o), trt$o)                                            # 46 districts
  geo <- GEO52                                                                        # embedded geography (section 0.1)
  mets <- c("xs_d", "xs_t", "xs_t23", "obs_d_km", "min_d_km", "obs_t", "min_t", "vol", "p90", "tot_d", "tot_t23",
            if (two_spec) c("xs_d_m", "xs_t_m"))
  mk_ev <- function(clock) { x <- copy(px); x[, ev := ymn(ym) - ymn(clock)]; x }
  base_idx <- function(x) {
    b <- x[ev %in% -12:-1, lapply(.SD, mean), .SDcols = mets, by = o]
    setnames(b, mets, paste0("b_", mets))
    x <- merge(x, b, by = "o")
    for (m in mets) x[, paste0("i_", m) := 100 * get(m) / get(paste0("b_", m))]
    x
  }
  ## screen on pre-opening data only: keep districts whose pre-opening excess is positive in distance and in time
  elig <- function(clock) {
    x <- mk_ev(clock)[ev %in% -12:-1, .(b_d = mean(xs_d), b_t = mean(xs_t)), by = o]
    x[b_d > 0 & b_t > 0, o]
  }
  pool_of <- function(clock) intersect(pool_raw, elig(clock))
  ## difference of differences of the index (points of the pre-opening level)
  did_one <- function(x, target, met, controls, agg = median) {
    im <- paste0("i_", met)
    tr <- x[o == target, .(ev, y = get(im))]
    ct <- x[o %chin% controls, .(yc = agg(get(im))), by = ev]
    g <- merge(tr, ct, by = "ev")[, gap := y - yc]
    pre <- g[ev %in% -12:-1, gap]; post <- g[ev %in% POST, gap]
    if (length(pre) < 10 || length(post) < 10) return(NULL)
    tt <- tryCatch(t.test(post, pre), error = function(e) NULL)   # a constant index (fixed minimum) has no t interval
    data.table(met = met, did = mean(post) - mean(pre),
               lo = if (is.null(tt)) mean(post) - mean(pre) else tt$conf.int[1],
               hi = if (is.null(tt)) mean(post) - mean(pre) else tt$conf.int[2])
  }
  own_change <- function(x, target, met) {            # % change of the district's own mean, post vs pre
    a <- x[o == target & ev %in% -12:-1, mean(get(met))]
    b <- x[o == target & ev %in% POST, mean(get(met))]
    100 * (b / a - 1)
  }
  res <- rbindlist(lapply(seq_len(nrow(trt)), function(i) {
    x <- base_idx(mk_ev(trt$open0[i])); pl <- pool_of(trt$open0[i])
    rbindlist(lapply(c("xs_d", "xs_t", "xs_t23", "obs_d_km", "min_d_km", "obs_t", "min_t", "vol", "p90", "tot_d", "tot_t23"), function(m) {
      r <- did_one(x, trt$o[i], m, pl); if (is.null(r)) return(NULL)
      ctl <- median(sapply(pl, function(cc) own_change(x, cc, m)))
      cbind(data.table(o = trt$o[i], name = trt$name[i], n_ctl = length(pl)), r,
            own_pct = own_change(x, trt$o[i], m), ctl_pct = ctl)
    }))
  }))
  fwrite(res, file.path(outdir, "tab_xc2.csv"))

  ## the comparison median's change term, so that Change = (district's own change) - (this term) can be rebuilt
  ctl_terms <- rbindlist(lapply(unique(trt$open0), function(ck) {
    xx <- base_idx(mk_ev(ck)); pl <- pool_of(ck)
