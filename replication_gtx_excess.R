## For each sample day the raw file (one csv, EUC-KR, about 6 million rows) is reduced to the cells that matter:
## trip purpose 1 (commute), domestic residents, origin and destination in Seoul (11), Incheon (28) or
## Gyeonggi (41). Within each origin-destination pair we keep three sums: commuters, commuters x reported
## distance (m), commuters x reported time (min). Output: OD1_DIR/od1_YYYYMMDD.csv.gz, no header, columns
## o,d,cnt,dw,tw (cnt to 2 decimals, dw and tw to 1 decimal).
OA_URL <- "https://datafile.seoul.go.kr/bigfile/iot/inf/nio_download.do?&useCache=false"
DOMESTIC_EUCKR <- as.raw(c(0xB3, 0xBB, 0xB1, 0xB9, 0xC0, 0xCE))                 # the label for domestic residents in EUC-KR
DOMESTIC_UTF8  <- as.raw(c(0xEB, 0x82, 0xB4, 0xEA, 0xB5, 0xAD, 0xEC, 0x9D, 0xB8)) # the same label in UTF-8
od1_file <- function(day, dir = OD1_DIR) file.path(dir, paste0("od1_", day, ".csv.gz"))

fetch_zip <- function(day, zipfile) {          # POST request used by the portal's download button
  body <- sprintf("infId=OA-22300&seqNo=&seq=%s&infSeq=1", substring(day, 3))     # seq = YYMMDD
  for (attempt in 1:3) {
    system2("curl", c("-s", "--retry", "3", "--retry-delay", "4", "-X", "POST", shQuote(OA_URL),
                      "--data", shQuote(body), "-o", shQuote(zipfile)))
    ok <- file.exists(zipfile) && file.size(zipfile) > 1e6 && identical(readBin(zipfile, "raw", 2L), as.raw(c(0x50, 0x4B)))   # "PK"
    if (ok) return(TRUE)
    Sys.sleep(5)
  }
  FALSE
}
aggregate_zip <- function(zipfile) {
  tmp <- tempfile("oa22300_"); dir.create(tmp)
  on.exit(unlink(tmp, recursive = TRUE), add = TRUE)
  csv <- utils::unzip(zipfile, exdir = tmp)
  stopifnot(length(csv) == 1L)
  x <- fread(csv, header = TRUE, select = c(1, 2, 5, 7, 8, 9, 10), encoding = "Latin-1",
             colClasses = list(character = c(1, 2, 5)))
  setnames(x, c("o", "d", "nat", "purpose", "dist", "time", "cnt"))
  keep_nat <- Filter(function(s) { r <- charToRaw(s); identical(r, DOMESTIC_EUCKR) || identical(r, DOMESTIC_UTF8) }, unique(x$nat))
  stopifnot(length(keep_nat) >= 1L)
  x <- x[purpose == 1 & nat %chin% keep_nat & substr(o, 1, 2) %chin% c("11", "28", "41") & substr(d, 1, 2) %chin% c("11", "28", "41")]
  x[, .(cnt = sum(cnt), dw = sum(cnt * dist), tw = sum(cnt * time)), by = .(o, d)]
}
write_od1 <- function(x, file) {
  dir.create(dirname(file), recursive = TRUE, showWarnings = FALSE)
  con <- gzfile(file, "w"); on.exit(close(con), add = TRUE)
  writeLines(sprintf("%s,%s,%.2f,%.1f,%.1f", x$o, x$d, x$cnt, x$dw, x$tw), con)
}
read_od1 <- function(file) {
  cn <- c("o", "d", "cnt", "dw", "tw")
  if (requireNamespace("R.utils", quietly = TRUE)) {
    fread(file, header = FALSE, col.names = cn, colClasses = list(character = 1:2))
  } else {
    setDT(read.csv(gzfile(file), header = FALSE, col.names = cn, colClasses = c("character", "character", "numeric", "numeric", "numeric")))
  }
}
