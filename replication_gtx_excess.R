  ## moving-block bootstrap and block-permutation p (serial correlation of the monthly gap makes the t interval too narrow)
  set.seed(SEED)
  mbb_gap <- function(x, target, met, controls, agg = median) {
    im <- paste0("i_", met)
    tr <- x[o == target, .(ev, y = get(im))]
    ct <- x[o %chin% controls, .(yc = agg(get(im))), by = ev]
    merge(tr, ct, by = "ev")[order(ev)][ev %in% c(-12:-1, POST)][, .(ev, gap = y - yc, post = as.integer(ev >= 0))]
  }
  ## (a) interval: resample 4-month blocks within the pre and within the post window, recompute post mean - pre mean
  mbb_ci <- function(g, L = 4L, B = 4000L) {
    blk <- function(v) {
      n <- length(v); nb <- ceiling(n / L)
      st <- sample(seq_len(n - L + 1), nb, replace = TRUE)
      v[as.vector(sapply(st, function(s) s:(s + L - 1)))[1:n]]
    }
    gp <- g[post == 1, gap]; gq <- g[post == 0, gap]
    bs <- replicate(B, mean(blk(gp)) - mean(blk(gq)))
    c(lo = unname(quantile(bs, .025)), hi = unname(quantile(bs, .975)))
  }
  ## (b) null distribution: circularly shift the 24-month gap series and relabel pre/post -> block-permutation p
  blk_perm_p <- function(g, est, B = 4000L) {
    n <- nrow(g); v <- g$gap; pst <- g$post
    null <- replicate(B, {
      k <- sample.int(n, 1L)
      vv <- v[c(k:n, seq_len(k - 1))]
      mean(vv[pst == 1]) - mean(vv[pst == 0])
    })
    (1 + sum(abs(null) >= abs(est))) / (1 + B)
  }
  infer <- rbindlist(lapply(trt$name, function(nm) {
    i <- which(trt$name == nm); x <- base_idx(mk_ev(trt$open0[i])); pl <- pool_of(trt$open0[i])
    rbindlist(lapply(c("xs_d", "xs_t", "xs_t23", "obs_t", "min_d_km", "tot_d", "tot_t23"), function(m) {
      g <- mbb_gap(x, trt$o[i], m, pl)
      d <- res[name == nm & met == m, did]
      b <- mbb_ci(g); pp <- blk_perm_p(g, d)
      p <- plc[clock == trt$open0[i] & met == m, did]
      data.table(name = nm, met = m, did = round(d, 2),
                 t_lo = round(res[name == nm & met == m, lo], 2), t_hi = round(res[name == nm & met == m, hi], 2),
                 mbb_lo = round(b["lo"], 2), mbb_hi = round(b["hi"], 2),
                 perm_p = round(pp, 3),   # 24-month circular shift: smallest attainable p = 2/24
                 ri_p = if (length(p)) round((1 + sum(abs(p) >= abs(d))) / (1 + length(p)), 3) else NA_real_)
    }))
  }))
  fwrite(infer, file.path(outdir, "infer_xc.csv"))

