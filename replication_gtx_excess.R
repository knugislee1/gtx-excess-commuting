      tr <- x[o == target, .(ev, y = i)]; ct <- x[o %chin% controls, .(yc = median(i)), by = ev]; g <- merge(tr, ct, by = "ev")
      mean(g[ev %in% POST, y - yc]) - mean(g[ev %in% -12:-1, y - yc])
    }
    rbindlist(lapply(c("xs_d", "xs_t23", "xs_t", "xm_d", "xm_t23", "xm_t"), function(met) {
      d <- one(met, PAJU, pool); z <- sapply(pool, function(j) one(met, j, setdiff(pool, j)))
      data.table(measure = met, did = round(d, 3), rank = 1 + sum(z >= d), p = round((1 + sum(abs(z) >= abs(d))) / 45, 3))
    }))
  }
  res <- list(); t0 <- Sys.time()
  for (rule in c("R0_current", "R1_preopening_mean", "R2_exclude")) {
    cost <- if (rule == "R1_preopening_mean") cost1 else cost0
